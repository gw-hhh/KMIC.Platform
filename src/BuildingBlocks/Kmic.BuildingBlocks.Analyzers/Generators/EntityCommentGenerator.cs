using System.Collections.Immutable;
using System.Text;
using System.Xml.Linq;
using Kmic.BuildingBlocks.Analyzers.Common;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Kmic.BuildingBlocks.Analyzers.Generators;

/// <summary>
/// 把实体与值对象公开属性的 XML 注释（summary）在编译时收集为一张表，模型构建时写成数据库列注释
/// </summary>
/// <remarks>
/// 列注释与代码注释只维护一份（05-03 第 3.9 节）；不在运行时读取 .xml 文档文件：部署时少了它，模型就会与迁移快照不一致
/// </remarks>
[Generator(LanguageNames.CSharp)]
public sealed class EntityCommentGenerator : IIncrementalGenerator
{
    /// <summary>
    /// 生成的类型名，框架按这个名字在实体所在程序集中查找
    /// </summary>
    public const string GeneratedTypeName = "Kmic.Generated.EntityComments";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var comments = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax or RecordDeclarationSyntax,
                static (syntax, ct) => Collect(syntax, ct))
            .SelectMany(static (entries, _) => entries)
            .Collect();

        context.RegisterSourceOutput(comments, static (output, entries) => Emit(output, entries));
    }

    private static ImmutableArray<(string Key, string Comment)> Collect(GeneratorSyntaxContext syntax, CancellationToken ct)
    {
        if (syntax.SemanticModel.GetDeclaredSymbol(syntax.Node, ct) is not INamedTypeSymbol type || !IsEntityOrValueObject(syntax.SemanticModel.Compilation, type))
        {
            return [];
        }

        var builder = ImmutableArray.CreateBuilder<(string, string)>();
        foreach (var property in type.GetMembers().OfType<IPropertySymbol>())
        {
            if (property is { DeclaredAccessibility: Accessibility.Public, IsStatic: false, IsIndexer: false }
                && Summary(property.GetDocumentationCommentXml(cancellationToken: ct)) is { Length: > 0 } summary)
            {
                builder.Add(($"{MetadataName(type)}.{property.Name}", summary));
            }
        }

        return builder.ToImmutable();
    }

    private static bool IsEntityOrValueObject(Compilation compilation, INamedTypeSymbol type) =>
        type.IsRecord || KnownTypes.InheritsFrom(type, compilation.GetTypeByMetadataName(KnownTypes.Entity));

    // 与反射的 Type.FullName 一致：嵌套类型用 +
    private static string MetadataName(INamedTypeSymbol type)
    {
        var name = type.MetadataName;
        for (var outer = type.ContainingType; outer is not null; outer = outer.ContainingType)
        {
            name = $"{outer.MetadataName}+{name}";
        }

        return type.ContainingNamespace is { IsGlobalNamespace: false } ns ? $"{ns.ToDisplayString()}.{name}" : name;
    }

    // 只取 summary 的文字：引用写成被引用成员的名字，空白合并为一个空格
    private static string? Summary(string? xml)
    {
        if (string.IsNullOrWhiteSpace(xml))
        {
            return null;
        }

        try
        {
            var summary = XElement.Parse(xml).Element("summary");
            if (summary is null)
            {
                return null;
            }

            foreach (var reference in summary.Descendants().ToList())
            {
                if (reference.Attribute("cref")?.Value is { } cref)
                {
                    reference.ReplaceWith(cref[(cref.LastIndexOfAny([':', '.']) + 1)..]);
                }
            }

            return string.Join(" ", summary.Value.Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries));
        }
        catch (System.Xml.XmlException)
        {
            // 写错的 XML 注释由编译器的文档警告报出，这里跳过即可
            return null;
        }
    }

    private static void Emit(SourceProductionContext output, ImmutableArray<(string Key, string Comment)> entries)
    {
        if (entries.IsDefaultOrEmpty)
        {
            return;
        }

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        source.AppendLine("namespace Kmic.Generated;");
        source.AppendLine();
        source.AppendLine("[global::System.CodeDom.Compiler.GeneratedCode(\"Kmic.BuildingBlocks.Analyzers\", \"1.0.0\")]");
        source.AppendLine("internal static class EntityComments");
        source.AppendLine("{");
        source.AppendLine("    public static global::System.Collections.Generic.IReadOnlyDictionary<string, string> Properties { get; } =");
        source.AppendLine("        new global::System.Collections.Generic.Dictionary<string, string>(global::System.StringComparer.Ordinal)");
        source.AppendLine("        {");

        // 分部类型会出现多次，只保留一份；按键排序让生成结果稳定
        foreach (var (key, comment) in entries.GroupBy(e => e.Key, StringComparer.Ordinal).Select(g => g.First()).OrderBy(e => e.Key, StringComparer.Ordinal))
        {
            source.Append("            [").Append(SymbolDisplay.FormatLiteral(key, quote: true)).Append("] = ")
                .Append(SymbolDisplay.FormatLiteral(comment, quote: true)).AppendLine(",");
        }

        source.AppendLine("        };");
        source.AppendLine("}");
        output.AddSource("EntityComments.g.cs", source.ToString());
    }
}
